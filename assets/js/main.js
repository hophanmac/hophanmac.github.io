  const defaultLang = "vi";
  const langButtons = document.querySelectorAll(".lang-btn");

  const applyTranslations = (lang) => {
    const chosen = translations[lang] ? lang : defaultLang;
    document.documentElement.lang = chosen;

    document.querySelectorAll("[data-i18n]").forEach((el) => {
      const key = el.getAttribute("data-i18n");
      if (translations[chosen][key]) {
        el.textContent = translations[chosen][key];
      }
    });

    document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
      const key = el.getAttribute("data-i18n-placeholder");
      if (translations[chosen][key]) {
        el.setAttribute("placeholder", translations[chosen][key]);
      }
    });

    langButtons.forEach((btn) => {
      btn.classList.toggle("active", btn.dataset.lang === chosen);
    });

    localStorage.setItem("siteLang", chosen);
  };

  langButtons.forEach((btn) => {
    btn.addEventListener("click", () => applyTranslations(btn.dataset.lang));
  });

  const savedLang = localStorage.getItem("siteLang") || defaultLang;
  applyTranslations(savedLang);

  const menuToggle = document.getElementById("menu-toggle");
  const menu = document.getElementById("site-menu");

  if (menuToggle && menu) {
    menuToggle.addEventListener("click", () => {
      const isOpen = menu.classList.toggle("open");
      menuToggle.setAttribute("aria-expanded", String(isOpen));
    });

    document.addEventListener("click", (event) => {
      const target = event.target;
      if (!menu.contains(target) && !menuToggle.contains(target)) {
        menu.classList.remove("open");
        menuToggle.setAttribute("aria-expanded", "false");
      }
    });
  }

  const contactForm = document.getElementById("contact-form");

